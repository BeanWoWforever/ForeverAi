function T.norm(s)
    s = tostring(s or ""):lower()
    s = s:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", "")
    s = s:gsub("'", ""):gsub("[^%w%s]", " ")
    s = s:gsub("%s+", " ")
    return strtrim and strtrim(s) or s:match("^%s*(.-)%s*$")
end

-- Expand slang word-by-word, return the normalized expanded string.
function T.expand(s)
    local out = {}
    -- "just hit 60" / "dinged 40" mean reaching a level, not the hit stat
    local n = T.norm(s):gsub("hit (%d+)", "reached level %1"):gsub("dinged? (%d+)", "reached level %1")
    for w in n:gmatch("%S+") do
        out[#out + 1] = T.slang[w] or w
    end
    return table.concat(out, " ")
end

-- Meaningful tokens (expanded, stopwords dropped, simple plural trim).
function T.tokens(s)
    local list, seen = {}, {}
    for word in T.expand(s):gmatch("%S+") do
        local w = word
        if not T.stop[w] then
            if #w > 4 and w:sub(-1) == "s" and not w:find("ss$") then w = w:sub(1, -2) end
            if not seen[w] then seen[w] = true; list[#list + 1] = w end
        end
    end
    return list, seen
end

-- Collapse a question that was pasted twice ("...ASAPCAN YOU GIVE ME..." repeated) and duplicate sentences.
function T.dedupe(raw)
    local s = tostring(raw or ""):gsub("%s+", " ")
    s = s:match("^%s*(.-)%s*$")
    local n = #s
    if n >= 30 then
        local lower = s:lower()
        for cut = math.floor(n / 2) - 3, math.floor(n / 2) + 3 do
            if cut > 10 and lower:sub(1, 25) == lower:sub(cut + 1, cut + 25) then
                return s:sub(1, cut)
            end
        end
    end
    local seen, parts = {}, {}
    for sent in (s .. "."):gmatch("([^%.%?!]+[%.%?!])") do
        local k = sent:lower():gsub("%W", "")
        if k ~= "" and not seen[k] then seen[k] = true; parts[#parts + 1] = sent end
    end
    return #parts > 0 and table.concat(parts, " "):gsub("%.$", "") or s
end

