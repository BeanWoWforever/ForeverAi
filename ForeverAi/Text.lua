-- Pull "what am I talking about" context out of a messy question: profession, a skill number vs character level.
function T.context(raw)
    local q = T.norm(raw)
    local info = {}
    for w in q:gmatch("%S+") do
        if T.professions[w] and not info.profession then info.profession = T.professions[w] end
    end
    if q:find("first aid") then info.profession = info.profession or "first aid" end
    local num = tonumber(q:match("level (%d+)") or q:match("lvl (%d+)") or q:match("skill (%d+)") or q:match("at (%d+)")
        or q:match("im (%d+)") or q:match("for (%d+)") or q:match("(%d+) skill") or q:match("(%d+) " .. (info.profession or "~~")))
    if num then
        if num > 60 or (info.profession and not q:find("character")) then info.skill = num else info.level = num end
    end
    return info
end

function T.words(s)
    local t = {}
    for w in T.norm(s):gmatch("%S+") do if not T.stop[w] then t[#t + 1] = w end end
    return t
end

-- Strip RestedXP/other addon colour and texture markup down to readable text.
function T.clean(s)
    s = tostring(s or "")
    s = s:gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|cRXP_[%u_]-_", ""):gsub("|r", "")
    s = s:gsub("|T.-|t", ""):gsub("|A.-|a", ""):gsub("|H.-|h(.-)|h", "%1")
    s = s:gsub("%s+", " ")
    return s:match("^%s*(.-)%s*$")
end

